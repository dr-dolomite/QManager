#!/bin/sh
. /usr/lib/qmanager/cgi_base.sh
# Cadence tables and the platform adapter (config store, flag paths) come from
# conn_state.sh. Guarded: a missing library must not abort the CGI (a `.` on a
# missing file kills a BusyBox script); the check below answers internal_error.
[ -f /usr/lib/qmanager/conn_state.sh ] && . /usr/lib/qmanager/conn_state.sh
# =============================================================================
# connection_quality.sh - CGI Endpoint: Connection Quality settings (GET + POST)
# =============================================================================
# GET:  Settings (sensitivity, 4 probe targets, latency/loss thresholds), the
#       cadence of the stored sensitivity, the sensitivity/preset tables, the
#       live per-slot probe state (contract 9A), the last cleared outage
#       (Amendment 3 A3.1) and is_default. Never writes config.
# POST: action=save_probe       {sensitivity, targets[4]}  -> ping reload flag
#       action=save_thresholds  {latency{preset,custom_ms?}, loss{preset,custom_pct?}}
#                               -> poller (quality) + watchdog reload flags
#
# Storage goes through the platform adapter (cfg_get / cfg_set / cfg_set_list):
# connection_quality sensitivity, targets (list), latency_preset,
# latency_custom_ms, loss_preset, loss_custom_pct. Only the new key names are
# written. The cadence tables are generated by conn_state.sh (one copy).
#
# Contract: docs/plans/2026-11-07-cq-watchdog-contracts.md section 5.1 / 5.2,
# Amendment 1 (A) and Amendment 3 (A3.1).
#
# Endpoint: GET/POST /cgi-bin/quecmanager/monitoring/connection_quality.sh
# Install location: /www/cgi-bin/quecmanager/monitoring/connection_quality.sh
# =============================================================================

qlog_init "cgi_connection_quality"
cgi_headers
cgi_handle_options

CQ_SLOTS_FILE="/tmp/qmanager_ping_slots.json"
CQ_LAST_OUTAGE_FILE="/tmp/qmanager_last_outage"
CQ_DEFAULT_T1="1.1.1.1"
CQ_DEFAULT_T2="8.8.8.8"
CQ_DEFAULT_T3="2606:4700:4700::1111"
CQ_DEFAULT_T4="cloudflare.com"

if ! command -v cfg_get >/dev/null 2>&1 || ! command -v conn_state_cadence >/dev/null 2>&1 \
    || ! command -v plat_flag_raise >/dev/null 2>&1; then
    jq -n '{success:false, error:"internal_error", detail:"platform library unavailable"}'
    exit 0
fi

# invalid_field <field> <detail>: the validation reply. Called before anything
# is staged, so there is nothing to revert.
invalid_field() {
    jq -n --arg field "$1" --arg detail "$2" \
        '{success:false, error:"invalid_field", field:$field, detail:$detail}'
    exit 0
}

save_failed() {
    cfg_revert >/dev/null 2>&1
    jq -n '{success:false, error:"save_failed", detail:"The settings could not be saved"}'
    exit 0
}

# cq_int_in <lo> <hi> <val>: prints val without leading zeros when it is plain
# decimal digits within lo..hi (rc 0), else rc 1. The length guard keeps the
# arithmetic test in range.
cq_int_in() {
    local v
    v="$3"
    case "$v" in ''|*[!0-9]*) return 1 ;; esac
    while [ "${#v}" -gt 1 ] && [ "${v#0}" != "$v" ]; do
        v="${v#0}"
    done
    [ "${#v}" -le "${#2}" ] || return 1
    [ "$v" -ge "$1" ] && [ "$v" -le "$2" ] || return 1
    printf '%s' "$v"
}

# cq_body_ok: rc 0 when CONTENT_LENGTH is unset/empty (cgi_read_post then answers
# no_body) or a plain number up to 8192; rc 1 for a longer or non-numeric length.
# Checked before the body is read so a large POST never reaches dd.
cq_body_ok() {
    local n
    n="$CONTENT_LENGTH"
    [ -n "$n" ] || return 0
    case "$n" in *[!0-9]*) return 1 ;; esac
    while [ "${#n}" -gt 1 ] && [ "${n#0}" != "$n" ]; do
        n="${n#0}"
    done
    [ "${#n}" -le 4 ] && [ "$n" -le 8192 ]
}

# cq_target_ok <host>: IPv4 literal, IPv6 literal or hostname. Charset
# [0-9A-Za-z.:%-], 1-128 chars, no leading '-' (it would be read as an option by
# ping). The charset has no shell metacharacter and no space.
cq_target_ok() {
    case "$1" in ''|-*) return 1 ;; esac
    [ "${#1}" -le 128 ] || return 1
    case "$1" in *[!0-9A-Za-z.:%-]*) return 1 ;; esac
    return 0
}

# cq_uptime: CQ_UP = integer seconds since boot (the writers' mono clock), or empty.
cq_uptime() {
    CQ_UP=""
    { read -r CQ_UP _cq_idle < /proc/uptime; } 2>/dev/null
    CQ_UP="${CQ_UP%%.*}"
    case "$CQ_UP" in ''|*[!0-9]*) CQ_UP="" ;; esac
}

# =============================================================================
# GET
# =============================================================================
if [ "$REQUEST_METHOD" = "GET" ]; then
    qlog_debug "Fetching connection quality settings"

    # --- Sensitivity + cadence (stored value; unknown reads relaxed) ---
    conn_state_cadence
    sensitivity="$CQ_CFG_SENSITIVITY"

    # --- Targets: stored slot when valid, else the default for that slot ---
    t1="$CQ_DEFAULT_T1"
    t2="$CQ_DEFAULT_T2"
    t3="$CQ_DEFAULT_T3"
    t4="$CQ_DEFAULT_T4"
    tlist=$(cfg_get_list connection_quality targets)
    ti=0
    while IFS= read -r tline; do
        ti=$((ti + 1))
        cq_target_ok "$tline" || continue
        case "$ti" in
            1) t1="$tline" ;;
            2) t2="$tline" ;;
            3) t3="$tline" ;;
            4) t4="$tline" ;;
        esac
    done <<EOF
$tlist
EOF

    # --- Thresholds ---
    lat_preset=$(cfg_get connection_quality latency_preset)
    loss_preset=$(cfg_get connection_quality loss_preset)
    lat_custom=$(cfg_get connection_quality latency_custom_ms)
    loss_custom=$(cfg_get connection_quality loss_custom_pct)

    is_default="false"
    [ -z "$lat_preset" ] && [ -z "$loss_preset" ] && is_default="true"

    lat_custom=$(cq_int_in 1 10000 "$lat_custom") || lat_custom=""
    loss_custom=$(cq_int_in 1 100 "$loss_custom") || loss_custom=""

    case "$lat_preset" in
        standard|tolerant|very-tolerant) ;;
        custom) [ -n "$lat_custom" ] || lat_preset="tolerant" ;;
        *) lat_preset="tolerant" ;;
    esac
    case "$loss_preset" in
        standard|tolerant|very-tolerant) ;;
        custom) [ -n "$loss_custom" ] || loss_preset="tolerant" ;;
        *) loss_preset="tolerant" ;;
    esac

    tables_json=$(conn_state_tables_json)

    # --- Live probe state (contract 9A): fresh cache only ---
    live_reach="null"
    live_leg=0
    live_slots='[{"state":"standby","rtt_ms":null},{"state":"standby","rtt_ms":null},{"state":"standby","rtt_ms":null},{"state":"standby","rtt_ms":null}]'
    if conn_state_read; then
        case "$CQ_REACHABLE" in true|false) live_reach="$CQ_REACHABLE" ;; esac
        case "$CQ_LAST_LEG" in [0-4]) live_leg="$CQ_LAST_LEG" ;; esac
        cq_uptime
        if [ -f "$CQ_SLOTS_FILE" ]; then
            slots_read=$(jq -c --argjson up "${CQ_UP:-0}" --argjson th "$CQ_STALE_THRESHOLD" \
                --arg gate "${CQ_MONO:+1}" '
                def okstate: . == "ok" or . == "miss" or . == "skipped" or . == "standby";
                if type == "object"
                    and ((.slots // null) | type) == "array"
                    and (.slots | length) == 4
                    and all(.slots[]; type == "object" and (.state | type == "string" and okstate)
                                      and ((.rtt_ms | type) == "number" or .rtt_ms == null))
                    and ($gate == "" or ((.mono | type) == "number" and .mono <= $up and ($up - .mono) <= $th))
                then [.slots[] | {state: .state, rtt_ms: .rtt_ms}]
                else empty end' "$CQ_SLOTS_FILE" 2>/dev/null </dev/null)
            [ -n "$slots_read" ] && live_slots="$slots_read"
        fi
    fi

    # --- Last cleared outage (this boot): "<secs> <end_mono> <changed|-> ..." ---
    last_outage="null"
    if [ -f "$CQ_LAST_OUTAGE_FILE" ]; then
        lo_d=""
        lo_e=""
        lo_c=""
        { read -r lo_d lo_e lo_c lo_rest < "$CQ_LAST_OUTAGE_FILE"; } 2>/dev/null
        lo_d=$(cq_int_in 0 99999999 "$lo_d") && lo_e=$(cq_int_in 0 2147483647 "$lo_e") || lo_d=""
        cq_uptime
        if [ -n "$lo_d" ] && [ -n "$CQ_UP" ] && [ "$lo_e" -le "$CQ_UP" ]; then
            case "$lo_c" in true|false) ;; *) lo_c="null" ;; esac
            last_outage=$(jq -n --argjson d "$lo_d" --argjson ago "$((CQ_UP - lo_e))" \
                --argjson c "$lo_c" '{duration_s:$d, ended_ago_s:$ago, wan_changed:$c}')
        fi
    fi

    jq -n \
        --arg sensitivity "$sensitivity" \
        --arg t1 "$t1" --arg t2 "$t2" --arg t3 "$t3" --arg t4 "$t4" \
        --arg lat_preset "$lat_preset" \
        --argjson lat_custom "${lat_custom:-null}" \
        --arg loss_preset "$loss_preset" \
        --argjson loss_custom "${loss_custom:-null}" \
        --argjson interval "$CQ_CFG_INTERVAL_SEC" \
        --argjson fail_secs "$CQ_CFG_FAIL_SECS" \
        --argjson recover_secs "$CQ_CFG_RECOVER_SECS" \
        --argjson window "$CQ_CFG_WINDOW_SEC" \
        --argjson tables "$tables_json" \
        --argjson live_reach "$live_reach" \
        --argjson live_leg "$live_leg" \
        --argjson live_slots "$live_slots" \
        --argjson last_outage "$last_outage" \
        --argjson is_default "$is_default" \
        '{
            success: true,
            settings: {
                sensitivity: $sensitivity,
                targets: [$t1, $t2, $t3, $t4],
                latency: {preset: $lat_preset, custom_ms: $lat_custom},
                loss: {preset: $loss_preset, custom_pct: $loss_custom}
            },
            cadence: {interval_sec: $interval, fail_secs: $fail_secs,
                      recover_secs: $recover_secs, window_sec: $window},
            tables: $tables,
            live: {reachable: $live_reach, last_leg: $live_leg, slots: $live_slots},
            last_outage: $last_outage,
            is_default: $is_default
        }'
    exit 0
fi

# =============================================================================
# POST
# =============================================================================
if [ "$REQUEST_METHOD" = "POST" ]; then
    cq_body_ok || {
        cgi_error "payload_too_large" "Request body is larger than 8192 bytes"
        exit 0
    }
    cgi_read_post

    if ! printf '%s' "$POST_DATA" | jq -e 'type == "object"' >/dev/null 2>&1; then
        cgi_error "invalid_json" "Request body is not a JSON object"
        exit 0
    fi

    ACTION=$(printf '%s' "$POST_DATA" | jq -r '.action | if type == "string" then . else "" end')
    if [ -z "$ACTION" ]; then
        cgi_error "missing_action" "action field is required"
        exit 0
    fi

    # -------------------------------------------------------------------------
    # save_probe {sensitivity, targets[4]}
    # -------------------------------------------------------------------------
    if [ "$ACTION" = "save_probe" ]; then
        sens=$(printf '%s' "$POST_DATA" | jq -r '.sensitivity | if type == "string" then "s" + . else "x" end')
        case "$sens" in
            ssensitive|sregular|srelaxed|squiet) sens="${sens#s}" ;;
            *) invalid_field "sensitivity" "must be one of: sensitive, regular, relaxed, quiet" ;;
        esac

        # Strings are prefixed "s" so an empty slot survives the tab split; a
        # non-string is "x". @tsv escapes tab, newline and backslash.
        trow=$(printf '%s' "$POST_DATA" | jq -r '.targets
            | if type == "array" and length == 4
              then (map(if type == "string" then "s" + . else "x" end) | @tsv)
              else "bad" end')
        [ "$trow" != "bad" ] && [ -n "$trow" ] || invalid_field "targets" "must be an array of exactly 4 hosts"

        tab=$(printf '\t')
        IFS="$tab" read -r r1 r2 r3 r4 <<EOF
$trow
EOF
        ti=0
        for r in "$r1" "$r2" "$r3" "$r4"; do
            case "$r" in
                s*) tv="${r#s}" ;;
                *) invalid_field "targets[$ti]" "must be a string" ;;
            esac
            cq_target_ok "$tv" || invalid_field "targets[$ti]" \
                "must be an IPv4/IPv6 address or hostname: 1-128 characters of letters, digits, . : % -, not starting with -"
            case "$ti" in
                0) t1="$tv" ;;
                1) t2="$tv" ;;
                2) t3="$tv" ;;
                3) t4="$tv" ;;
            esac
            ti=$((ti + 1))
        done

        cfg_set connection_quality sensitivity "$sens" \
            && cfg_set_list connection_quality targets "$t1" "$t2" "$t3" "$t4" \
            && cfg_commit || save_failed

        plat_flag_raise "$PF_PING_RELOAD"
        qlog_info "Probe settings saved: sensitivity=$sens"
        echo '{"success":true}'
        exit 0
    fi

    # -------------------------------------------------------------------------
    # save_thresholds {latency{preset,custom_ms?}, loss{preset,custom_pct?}}
    # custom_* is required only when that preset is custom; with a named preset
    # it is ignored and the stored custom value is kept.
    # -------------------------------------------------------------------------
    if [ "$ACTION" = "save_thresholds" ]; then
        lat_preset=$(printf '%s' "$POST_DATA" | jq -r '.latency
            | if type == "object" then (.preset | if type == "string" then "s" + . else "x" end) else "x" end')
        case "$lat_preset" in
            sstandard|stolerant|svery-tolerant|scustom) lat_preset="${lat_preset#s}" ;;
            *) invalid_field "latency.preset" "must be one of: standard, tolerant, very-tolerant, custom" ;;
        esac
        lat_custom=""
        if [ "$lat_preset" = "custom" ]; then
            lat_custom=$(printf '%s' "$POST_DATA" | jq -r '.latency.custom_ms
                | if type == "number" and . == floor then (floor | tostring) else "x" end')
            lat_custom=$(cq_int_in 1 10000 "$lat_custom") \
                || invalid_field "latency.custom_ms" "must be an integer 1-10000 when the preset is custom"
        fi

        loss_preset=$(printf '%s' "$POST_DATA" | jq -r '.loss
            | if type == "object" then (.preset | if type == "string" then "s" + . else "x" end) else "x" end')
        case "$loss_preset" in
            sstandard|stolerant|svery-tolerant|scustom) loss_preset="${loss_preset#s}" ;;
            *) invalid_field "loss.preset" "must be one of: standard, tolerant, very-tolerant, custom" ;;
        esac
        loss_custom=""
        if [ "$loss_preset" = "custom" ]; then
            loss_custom=$(printf '%s' "$POST_DATA" | jq -r '.loss.custom_pct
                | if type == "number" and . == floor then (floor | tostring) else "x" end')
            loss_custom=$(cq_int_in 1 100 "$loss_custom") \
                || invalid_field "loss.custom_pct" "must be an integer 1-100 when the preset is custom"
        fi

        cfg_set connection_quality latency_preset "$lat_preset" || save_failed
        cfg_set connection_quality loss_preset "$loss_preset" || save_failed
        if [ -n "$lat_custom" ]; then
            cfg_set connection_quality latency_custom_ms "$lat_custom" || save_failed
        fi
        if [ -n "$loss_custom" ]; then
            cfg_set connection_quality loss_custom_pct "$loss_custom" || save_failed
        fi
        cfg_commit || save_failed

        # The poller (events) and the watchdog (recovery) consume the thresholds
        # through separate reload flags: raise both or one goes stale.
        plat_flag_raise "$PF_QUALITY_RELOAD"
        plat_flag_raise "$PF_WD_RELOAD"
        qlog_info "Quality thresholds saved: latency=$lat_preset loss=$loss_preset"
        echo '{"success":true}'
        exit 0
    fi

    cgi_error "unknown_action" "Unknown action: $ACTION"
    exit 0
fi

cgi_error "method_not_allowed" "Only GET and POST are supported"
